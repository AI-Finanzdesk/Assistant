export function dict(lang: Lang): Dict {
  return lang === "de" ? de : nl;
}

export function formatDate(value: string | null | undefined, lang: Lang, withTime = false) {
  if (!value) return "—";
  const d = new Date(value);
  return d.toLocaleString(lang === "de" ? "de-DE" : "nl-NL", {
    day: "numeric",
    month: "short",
    year: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit", timeZone: "Europe/Berlin" } : {}),
  });
}
